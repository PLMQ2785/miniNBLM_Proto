def generate(output: Path) -> None:
    """간호 주제들을 방해 문서로 저장하고 PDF 자원을 닫는다."""
    output.parent.mkdir(parents=True, exist_ok=True)
    document = fitz.open()
    for page_number, (title, *paragraphs) in enumerate(TOPICS, start=1):
        page = document.new_page(width=595, height=842)
        page.insert_text((48, 62), f"간호 실무 참고 주제 {page_number}", fontname="korea", fontsize=11)
        page.insert_text((48, 100), title, fontname="korea", fontsize=24)
        body = "\n\n".join(paragraphs * 3)
        remaining = page.insert_textbox(
            fitz.Rect(48, 140, 547, 760),
            body,
            fontname="korea",
            fontsize=11,
            lineheight=1.5,
        )
        if remaining < 0:
            raise RuntimeError(f"Distractor text did not fit: {title}")
    document.set_metadata(
        {
            "title": "Retrieval evaluation distractor nursing topics",
            "author": "miniNBLM evaluation generator",
        }
    )
    document.save(output, garbage=4, deflate=True)
    document.close()


if __name__ == "__main__":
    generate(Path("evaluation/retrieval_distractor_nursing_topics.pdf"))
